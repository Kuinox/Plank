using Microsoft.CodeAnalysis;

namespace Plank.InternalGen;

/// <summary>
/// Shares binary framing decisions while preserving the concrete byte-array loops and
/// generic memory loops. Moving these loops behind new calls changes JIT code layout.
/// </summary>
[Generator]
public sealed class BinaryRepresentationGenerator : IIncrementalGenerator
{
    static readonly KeyValuePair<string, string>[] FixedRepresentations =
    [
        new("FixedLenByteArray", "EncodingPrimitives.GetFixedLength(column)"),
        new("Int96", "12")
    ];

    static string FixedTypes => "column.PhysicalType is " + string.Join(" or ",
        FixedRepresentations.Select(r => "ParquetPhysicalType." + r.Key));

    static string FixedWidth
    {
        get
        {
            var expression = FixedRepresentations[0].Value;
            foreach (var representation in FixedRepresentations.Skip(1))
                expression = "column.PhysicalType == ParquetPhysicalType." + representation.Key
                    + " ? " + representation.Value + " : " + expression;
            return expression;
        }
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
        => context.RegisterPostInitializationOutput(static context => context.AddSource(
            "PlainEncoding.OptionalBinary.g.cs",
            "// <auto-generated/>\n#nullable enable\nusing System.Buffers.Binary;\n"
            + "using System.Runtime.CompilerServices;\nusing Plank.Schema;\n"
            + "namespace Plank.Writing.Encoding;\nstatic partial class PlainEncoding\n{\n"
            + Template.Replace("{{FIXED_TYPES}}", FixedTypes).Replace("{{FIXED_WIDTH}}", FixedWidth)
            + "}\n"));

    const string Template = """
    internal static void WriteOptionalValues<TRow, TRowAccess>(Column column, ReadOnlySpan<TRow> rows,
        int knownPayloadBytes, ref BufferWriter writer)
        where TRowAccess : IByteArrayRow<TRow>
    {
        if ({{FIXED_TYPES}} &&
            typeof(TRow) != typeof(byte[]))
        {
            var valueLength = {{FIXED_WIDTH}};
            for (var i = 0; i < rows.Length; i++)
            {
                if (!ByteArrayRows.TryGetPayload<TRow, TRowAccess>(column, in rows[i], out var payload))
                    continue;
                if (payload.Length != valueLength)
                    throw new InvalidOperationException($"Column '{column.Name}' expects {valueLength}-byte values.");
                writer.Write(payload);
            }
            return;
        }
        if (typeof(TRow) == typeof(byte[]))
        {
            WriteOptionalByteArrayPayloads(column,
                Unsafe.As<ReadOnlySpan<TRow>, ReadOnlySpan<byte[]>>(ref rows), knownPayloadBytes, ref writer);
            return;
        }

        WriteLengthPrefixedPayloads<TRow, TRowAccess>(column, rows, knownPayloadBytes, ref writer);
    }

    static void WriteOptionalByteArrayPayloads(Column column, ReadOnlySpan<byte[]> values,
        int knownPayloadBytes, ref BufferWriter writer)
    {
        if ({{FIXED_TYPES}})
        {
            var valueLength = {{FIXED_WIDTH}};
            var fixedByteCount = knownPayloadBytes;
            if (fixedByteCount < 0)
            {
                var presentCount = 0;
                for (var i = 0; i < values.Length; i++)
                    if (values[i] is not null)
                        presentCount++;
                fixedByteCount = checked(presentCount * valueLength);
            }

            var destination = writer.GetSpan(fixedByteCount);
            var offset = 0;
            for (var i = 0; i < values.Length; i++)
            {
                var value = values[i];
                if (value is null)
                    continue;
                if (value.Length != valueLength)
                    throw new InvalidOperationException(
                        $"Column '{column.Name}' expects fixed-length values of {valueLength} bytes, but got {value.Length}.");
                EncodingPrimitives.CopyPayload(value, destination[offset..]);
                offset += valueLength;
            }

            writer.Advance(offset);
            return;
        }

        var byteCount = knownPayloadBytes;
        if (byteCount < 0)
        {
            byteCount = 0;
            for (var i = 0; i < values.Length; i++)
                if (values[i] is { } value)
                    byteCount = checked(byteCount + sizeof(int) + value.Length);
        }

        if (byteCount == 0)
            return;

        var lengthPrefixedDestination = writer.GetSpan(byteCount);
        var lengthPrefixedOffset = 0;
        for (var i = 0; i < values.Length; i++)
        {
            var value = values[i];
            if (value is null)
                continue;
            BinaryPrimitives.WriteInt32LittleEndian(lengthPrefixedDestination[lengthPrefixedOffset..], value.Length);
            lengthPrefixedOffset += sizeof(int);
            EncodingPrimitives.CopyPayload(value, lengthPrefixedDestination[lengthPrefixedOffset..]);
            lengthPrefixedOffset += value.Length;
        }

        writer.Advance(lengthPrefixedOffset);
    }

""";
}
