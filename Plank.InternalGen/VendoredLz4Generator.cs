using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Plank.InternalGen;

// Keep the upstream files unchanged while preventing duplicate public K4os types
// when a consumer also references the original package.
[Generator]
public sealed class VendoredLz4Generator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider.Where(static f =>
            f.Path.Replace('\\', '/').Contains("/K4os.Compression.LZ4/src/K4os.Compression.LZ4/"));
        context.RegisterSourceOutput(files, static (output, file) =>
        {
            var source = file.GetText(output.CancellationToken)?.ToString();
            if (source is null) return;
            // All namespace references are qualified consistently in the upstream source.
            source = source.Replace("K4os.Compression.LZ4", "Plank.Vendored.LZ4");
            var root = CSharpSyntaxTree.ParseText(source).GetRoot();
            var rewritten = new InternalizeTypes().Visit(root)!.ToFullString();
            var path = file.Path.Replace('\\', '/');
            var relative = path.Substring(path.IndexOf("/src/K4os.Compression.LZ4/", StringComparison.Ordinal) + "/src/K4os.Compression.LZ4/".Length);
            output.AddSource("VendoredLz4." + relative.Replace('/', '.') + ".g.cs",
                SourceText.From("// <auto-generated/>\n" + rewritten, Encoding.UTF8));
        });
    }

    sealed class InternalizeTypes : CSharpSyntaxRewriter
    {
        public override SyntaxNode? VisitClassDeclaration(ClassDeclarationSyntax node) =>
            base.VisitClassDeclaration(IsTopLevel(node) ? node.WithModifiers(Internalize(node.Modifiers)) : node);
        public override SyntaxNode? VisitStructDeclaration(StructDeclarationSyntax node) =>
            base.VisitStructDeclaration(IsTopLevel(node) ? node.WithModifiers(Internalize(node.Modifiers)) : node);
        public override SyntaxNode? VisitEnumDeclaration(EnumDeclarationSyntax node) =>
            base.VisitEnumDeclaration(IsTopLevel(node) ? node.WithModifiers(Internalize(node.Modifiers)) : node);

        static bool IsTopLevel(MemberDeclarationSyntax node) => node.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax;
        static SyntaxTokenList Internalize(SyntaxTokenList modifiers)
        {
            foreach (var token in modifiers)
                if (token.IsKind(SyntaxKind.PublicKeyword))
                    return modifiers.Replace(token, SyntaxFactory.Token(token.LeadingTrivia, SyntaxKind.InternalKeyword, token.TrailingTrivia));
            return modifiers;
        }
    }
}
