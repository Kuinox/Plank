using System.Text;
using Microsoft.CodeAnalysis;

namespace Plank.InternalGen;

/// <summary>
/// The decimal representation manifest. Encoding kernels stay concrete: this emits ordinary
/// C# loops and calls, with no runtime registry, boxing, or conversion buffers.
/// </summary>
[Generator]
public sealed class DecimalRepresentationGenerator : IIncrementalGenerator
{
    // A representation must supply both directions. The generated consumers reference these
    // methods directly, so removing either direction is a compiler error.
    static readonly Representation[] Representations =
    [
        new("Int32", "sizeof(int)", "ToInt32", "FromInt32"),
        new("Int64", "sizeof(long)", "ToInt64", "FromInt64"),
        new("FixedLenByteArray", "checked((int)column.Options.TypeLength)", "WriteFixedBigEndian", "ReadBigEndian"),
        new("ByteArray", null, "WriteBigEndian", "ReadBigEndian")
    ];

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context =>
        {
            context.AddSource("ParquetDecimalConverter.Representations.g.cs", GenerateConversions());
            context.AddSource("PlainEncoding.Decimal.g.cs", GenerateWriter());
            context.AddSource("ColumnChunkReader.Decimal.g.cs", GenerateReader());
        });
    }

    static StringBuilder Header(string ns, string declaration)
        => new StringBuilder("// <auto-generated/>\n#nullable enable\n")
            .AppendLine("using System.Buffers.Binary;")
            .AppendLine("using System.Runtime.CompilerServices;")
            .AppendLine("using Plank.Schema;")
            .AppendLine("using Plank.BloomFilters;")
            .Append("namespace ").Append(ns).AppendLine(";")
            .Append(declaration).AppendLine("\n{");

    static string GenerateConversions()
    {
        var source = Header("Plank.Schema", "static partial class ParquetDecimalConverter");
        source.AppendLine("    internal static ReadOnlySpan<ParquetPhysicalType> PhysicalTypes => [");
        foreach (var representation in Representations)
            source.Append("        ParquetPhysicalType.").Append(representation.PhysicalType).AppendLine(",");
        source.AppendLine("    ];");
        source.AppendLine("    internal static bool SupportsPhysicalType(ParquetPhysicalType physicalType) => physicalType is");
        source.Append("        ").Append(string.Join(" or ", Representations.Select(r => "ParquetPhysicalType." + r.PhysicalType)))
            .AppendLine(";");

        // Retained append values are physical CLR values, not page-framed bytes. Binary
        // representations share an inverse; emit that overload only once.
        foreach (var representation in Representations.GroupBy(r => r.StorageType).Select(g => g.First()))
        {
            source.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            source.Append("    internal static decimal FromPhysical(").Append(representation.StorageType)
                .Append(" value, Column column) => ").Append(representation.FromPhysical).AppendLine("(value, column);");
        }

        source.AppendLine("    internal static ulong HashPhysical(Column column, decimal value)");
        source.AppendLine("    {");
        foreach (var representation in Representations)
        {
            if (representation.Width is not null)
                source.Append("        if (column.PhysicalType == ParquetPhysicalType.").Append(representation.PhysicalType).AppendLine(")");
            source.AppendLine("        {");
            if (representation.IsInteger)
                source.Append("            return ParquetBloomFilterHash.Hash(").Append(representation.ToPhysical).AppendLine("(value, column));");
            else if (representation.Width is not null)
            {
                source.Append("            var length = ").Append(representation.Width).AppendLine(";");
                source.AppendLine("            Span<byte> bytes = length <= 256 ? stackalloc byte[length] : new byte[length];");
                source.Append("            ").Append(representation.ToPhysical).AppendLine("(value, column, bytes);");
                source.AppendLine("            return ParquetBloomFilterHash.Hash(bytes);");
            }
            else
            {
                source.AppendLine("            Span<byte> bytes = stackalloc byte[16];");
                source.Append("            var count = ").Append(representation.ToPhysical).AppendLine("(value, column, bytes);");
                source.AppendLine("            return ParquetBloomFilterHash.Hash(bytes[..count]);");
            }
            source.AppendLine("        }");
        }
        source.AppendLine("    }\n}");
        return source.ToString();
    }

    static string GenerateWriter()
    {
        var source = Header("Plank.Writing.Encoding", "static partial class PlainEncoding");
        foreach (var representation in Representations)
        {
            source.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            source.Append("    static void WriteDecimal").Append(representation.PhysicalType)
                .Append("Values(Column column, ReadOnlySpan<decimal> values, ")
                .AppendLine(representation.IsInteger ? "Span<byte> destination)"
                    : representation.Width is not null ? "int valueLength, ref BufferWriter writer)" : "ref BufferWriter writer)");
            source.AppendLine("    {");
            if (representation.Width is not null)
            {
                if (representation.IsInteger)
                    source.Append("        var valueLength = ").Append(representation.Width).AppendLine(";");
                if (!representation.IsInteger)
                    source.AppendLine("        var byteCount = checked(values.Length * valueLength);");
            }
            else
            {
                source.AppendLine("        var byteCount = 0;");
                source.AppendLine("        for (var i = 0; i < values.Length; i++)");
                source.AppendLine("            byteCount = checked(byteCount + sizeof(int) + ParquetDecimalConverter.GetByteCount(values[i], column));");
            }
            if (!representation.IsInteger)
            {
                source.AppendLine("        if (byteCount == 0) return;");
                source.AppendLine("        var destination = writer.GetSpan(byteCount);");
            }
            if (representation.Width is null)
                source.AppendLine("        var offset = 0;");
            source.AppendLine("        for (var i = 0; i < values.Length; i++)");
            if (representation.IsInteger)
                source.Append("            BinaryPrimitives.Write").Append(representation.PhysicalType)
                    .Append("LittleEndian(destination[(i * valueLength)..], ParquetDecimalConverter.")
                    .Append(representation.ToPhysical).AppendLine("(values[i], column));");
            else if (representation.Width is not null)
                source.Append("            ParquetDecimalConverter.").Append(representation.ToPhysical)
                    .AppendLine("(values[i], column, destination.Slice(i * valueLength, valueLength));");
            else
            {
                source.AppendLine("        {");
                source.AppendLine("            var length = ParquetDecimalConverter.GetByteCount(values[i], column);");
                source.AppendLine("            BinaryPrimitives.WriteInt32LittleEndian(destination[offset..], length);");
                source.AppendLine("            offset += sizeof(int);");
                source.Append("            offset += ParquetDecimalConverter.").Append(representation.ToPhysical)
                    .AppendLine("(values[i], column, destination.Slice(offset, length));");
                source.AppendLine("        }");
            }
            if (!representation.IsInteger)
                source.Append("        writer.Advance(").Append(representation.Width is null ? "offset" : "byteCount").AppendLine(");");
            source.AppendLine("    }");
        }
        source.AppendLine("}");
        return source.ToString();
    }

    static string GenerateReader()
    {
        var source = Header("Plank.Reading.Logical.Internal", "static partial class ColumnChunkReader");
        source.AppendLine("    static bool TryDecodePlainDecimalValues(ReadOnlySpan<byte> payload, Column column, uint valueCount, Span<decimal> typed)");
        source.AppendLine("    {\n        switch (column.PhysicalType)\n        {");
        foreach (var representation in Representations)
        {
            source.Append("            case ParquetPhysicalType.").Append(representation.PhysicalType).AppendLine(":\n            {");
            if (representation.Width is not null)
            {
                source.Append("                var valueLength = ")
                    .Append(representation.IsInteger ? representation.Width : "GetFixedBinaryLength(column)").AppendLine(";");
                source.AppendLine("                ValidatePlainPayload(payload, valueCount, checked((uint)valueLength));");
                source.AppendLine("                for (var i = 0; i < typed.Length; i++)");
                source.Append("                    typed[i] = ParquetDecimalConverter.").Append(representation.FromPhysical).Append("(");
                if (representation.IsInteger)
                    source.Append("BinaryPrimitives.Read").Append(representation.PhysicalType)
                        .Append("LittleEndian(payload.Slice(i * valueLength, valueLength))");
                else
                    source.Append("payload.Slice(i * valueLength, valueLength)");
                source.AppendLine(", column);");
            }
            else
            {
                source.AppendLine("                var offset = 0;");
                source.AppendLine("                for (var i = 0; i < typed.Length; i++)\n                {");
                source.AppendLine("                    if (payload.Length - offset < sizeof(int))");
                source.AppendLine("                        throw new CorruptParquetException($\"Plain decimal payload ended before length prefix {i}.\");");
                source.AppendLine("                    var length = BinaryPrimitives.ReadInt32LittleEndian(payload[offset..]);");
                source.AppendLine("                    offset += sizeof(int);");
                source.AppendLine("                    if (length <= 0 || length > payload.Length - offset)");
                source.AppendLine("                        throw new CorruptParquetException($\"Plain decimal value {i} declares invalid length {length}.\");");
                source.Append("                    typed[i] = ParquetDecimalConverter.").Append(representation.FromPhysical)
                    .AppendLine("(payload.Slice(offset, length), column);");
                source.AppendLine("                    offset += length;\n                }");
            }
            source.AppendLine("                return true;\n            }");
        }
        source.AppendLine("            default: return false;\n        }\n    }\n}");
        return source.ToString();
    }

    sealed class Representation(string physicalType, string? width, string toPhysical, string fromPhysical)
    {
        internal string PhysicalType { get; } = physicalType;
        internal string? Width { get; } = width;
        internal string ToPhysical { get; } = toPhysical;
        internal string FromPhysical { get; } = fromPhysical;
        internal bool IsInteger => PhysicalType is "Int32" or "Int64";
        internal string StorageType => PhysicalType == "Int32" ? "int" : PhysicalType == "Int64" ? "long" : "ReadOnlySpan<byte>";
    }
}
